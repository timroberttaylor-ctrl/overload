// Inlines drizzle-kit's SQL migrations into a TypeScript module so the same
// migrations run in the app (expo-sqlite) and in Node tests (better-sqlite3)
// without a Babel/Metro .sql loader.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dir = 'src/db/migrations';
const journal = JSON.parse(readFileSync(join(dir, 'meta/_journal.json'), 'utf8'));
const migrations = {};
for (const e of journal.entries) {
  migrations['m' + String(e.idx).padStart(4, '0')] = readFileSync(join(dir, `${e.tag}.sql`), 'utf8');
}
const body = `// Generated by scripts/bundle-migrations.mjs from drizzle-kit output. Do not edit.\n` +
  `export const migrationBundle = ${JSON.stringify({ journal, migrations }, null, 2)} as const;\n`;
writeFileSync(join(dir, 'bundle.ts'), body);
console.log('bundled', journal.entries.length, 'migrations');
